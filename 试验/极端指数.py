"""极端指数入门：阈值怎么定、超阈怎么数

跑法（VS Code）：打开本文件 → Ctrl+S → Ctrl+Shift+B

数据：ERA5 2020 年 1/4/7/10 四个月，6 小时一个时次，共 492 个样本。
⚠️ 样本很少，这里只演示"怎么算"，结论不能当科学结论（原因见最后一段注释）。
"""
import sys
from pathlib import Path

import numpy as np
import xarray as xr

BASE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE / "src"))          # 复用仓库里的画图库，不重复写
from era5x import compute, io                  # noqa: E402
from era5x import plot as eplot                # noqa: E402

# ======================================================================
# 一、准备：读 4 个代表月的风速场
# ======================================================================
files = sorted((BASE / "data").glob("era5_*.nc"))
ds = io.load_era5_months(files)                # 内部已处理 valid_time / expver / 纬度顺序
ws = compute.wind_speed(ds).compute()          # 492 × 61 × 121，先算进内存（小，无所谓）
print(f"样本: {ws.sizes['time']} 个时次，网格 {ws.sizes['latitude']}×{ws.sizes['longitude']}")

# ======================================================================
# 二、方法 A：逐格点阈值（percentile per grid cell）
# ======================================================================
# ---- 【在哪个维度上算分位数】dim="time"：每个格点各自看自己的时间序列，
#      取它自己 95% 分位上的值作为"这个地方的极端阈值"。
#      结果形状 (61,121)：每个格点一个阈值，空间上不统一（大风区阈值天然更高）。
p95_cell = ws.quantile(0.95, dim="time")
# ---- 【超阈次数】逐时次比较再沿时间求和：每个格点有多少个时次超过了它自己的 p95。
overshoot_cell = (ws > p95_cell).sum("time")

# ======================================================================
# 三、方法 B：区域统一阈值（domain-wide threshold）
# ======================================================================
# ---- 【怎么得到"区域的时间序列"】先把空间压掉（区域平均），再对这条序列取分位数。
#      注意顺序：先 mean(空间) 再 quantile(时间)，得到一个标量阈值。
region_series = ws.mean(("latitude", "longitude"))
thr_region = float(region_series.quantile(0.95))
print(f"区域统一阈值 p95 = {thr_region:.2f} m/s")
print(f"逐格点阈值范围   = {float(p95_cell.min()):.2f} ~ {float(p95_cell.max()):.2f} m/s")
# ---- 【用统一阈值再去数】此时大风区会超很多次，静风区几乎不超——
#      这正是它和"逐格点"最关键的区别：统一阈值衡量的是"绝对强度"，
#      逐格点阈值衡量的是"相对于本地常态的异常程度"。
overshoot_region = (ws > thr_region).sum("time")

# ======================================================================
# 四、方法 C：绝对阈值（absolute threshold）
# ======================================================================
# ---- 【为什么还要绝对阈值】业务上常按风力等级卡：≥10.8 m/s 就是 6 级风，
#      和"本地 95 分位"是两套语言——前者可跨地区比较，后者只在本地说得通。
# ---- 【6 小时数据怎么折成"日"】一个时次代表 6 小时，4 个时次算一天；
#      这里用"超阈时次数 / 4"粗略折算成天数，精度有限，见最后一段。
thr_abs = 10.8
days_abs = (ws > thr_abs).sum("time") / 4.0
print(f"≥{thr_abs} m/s 的时次占比: {float((ws > thr_abs).mean()) * 100:.2f}%")

# ======================================================================
# 五、出图：三张对比
# ======================================================================
eplot.setup_style()                             # 中文字体 + 负号，仓库里已有，别重写
eplot.plot_map(p95_cell, BASE / "3_成果图" / "试验_极端阈值_p95.png",
               title="逐格点 p95 风速阈值（2020 四个月）", levels=np.arange(4, 12.5, 0.5))
# ---- 两个"超阈次数"场单位相同（次），可以共用一套色标放一个 2×1 图里对比
eplot.plot_panels(
    {"逐格点阈值（相对本地）": overshoot_cell,
     "区域统一阈值（绝对强度）": overshoot_region},
    BASE / "3_成果图" / "试验_极端超阈次数对比.png",
    suptitle="超阈时次数的两种算法（492 个时次中）",
    levels=np.arange(0, 61, 5), ncols=2,
    cbar_label="超阈时次数（次，共 492 个时次）",
)

# ======================================================================
# 六、把关键数字打出来，方便写笔记
# ======================================================================
print("\n--- 汇总 ---")
print(f"逐格点阈值下，平均超阈次数: {float(overshoot_cell.mean()):.1f} 次（理论值 492×5% ≈ 24.6）")
print(f"区域统一阈值下，平均超阈次数: {float(overshoot_region.mean()):.1f} 次")
print(f"两者差异最大的格点: {float((overshoot_cell - overshoot_region).max()):+.0f} 次")

# ======================================================================
# ⚠️ 为什么这份结果不能写进论文
# ======================================================================
# 1) 样本只有 492 个时次（4 个月），95 分位相当于"第 25 大的值"，极不稳定；
#    真正的极端指数至少要有 20–30 年（约 3 万个时次）。
# 2) 阈值必须用"基准期"算，再用到"研究期"上。这里用同一段数据算阈值又数超阈，
#    叫循环论证——超阈次数必然接近 5%，什么也证明不了。
# 3) 6 小时数据折算"天数"很粗（一天只有 4 个时次），日极值类指数要用逐小时或日值。
# 4) 只取了 1/4/7/10 四个月，季节代表性不足。
