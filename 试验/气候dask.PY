"""CMFD 40 年月平均：dask 分块 + 年际气候态

跑法（VS Code）：打开本文件 → Ctrl+S 保存 → Ctrl+Shift+B 运行当前文件。

这份文件同时也是「怎么读 nc 数据」的教材：
每一段前面有【为什么】，每行后面有【干什么】，照顺序读下来就能懂整条链路。
"""
from pathlib import Path

# ---- 【为什么用 Agg】matplotlib 默认后端要开窗口，脚本跑完会挂住等你去关窗口。
#      在 VS Code 任务里跑、或者以后在服务器上跑，必须用无界面后端。
#      注意顺序：必须在 import pyplot 之前设置，否则默认后端已经加载，设了也无效。
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

import numpy as np
import xarray as xr

# ---- 【为什么设字体】matplotlib 默认字体 DejaVu Sans 没有汉字，
#      标题和轴标签里的中文会渲染成方块/乱码——这不是编码错误，是缺字形。
#      按顺序找：微软雅黑 → 黑体 → DejaVu（拉丁兜底）。
plt.rcParams["font.sans-serif"] = ["Microsoft YaHei", "SimHei", "DejaVu Sans"]
# ---- 【为什么关掉 unicode_minus】负号默认用排版用的 U+2212，中文字体常常没有这个字形，
#      画差值图（有负数）时会变成方块。改成 ASCII 的 "-" 最稳。
plt.rcParams["axes.unicode_minus"] = False

# ---- 【为什么要从 __file__ 倒推】写死 D:\work\... 换台电脑就废；
#      从脚本自身位置往上两级，脚本放哪都能找到仓库根目录。
#      ...\era5-xinjiang\试验\气候dask.PY  →  parent=试验  →  parent.parent=仓库根
BASE = Path(__file__).resolve().parent.parent
# ---- 【Path 的 / 运算符】做路径拼接，Windows 上自动用 \，比手写 "\\" 少一个转义错误。
SRC = BASE / "data" / "wind_CMFD_V0106_B-01_01mo_010deg_197901-201812.nc"
OUT = BASE / "3_成果图" / "CMFD风速_1979-2018_年均序列.png"

# ======================================================================
# 第一步：读文件，并且让它"分块"
# ======================================================================
# ---- 【chunks 是整个脚本最关键的一个参数】
#      CMFD 是 480 月 × 400 行 × 700 列 × 4 字节 ≈ 537 MB。
#      不切块 → 一次性读进内存，20 年数据就是 6 GB，直接 MemoryError。
#      切 12   → 每块 12×400×700×4 ≈ 13 MB，dask 算到哪读到哪，内存占用跟总量无关。
# ---- 【为什么切 12】CMFD 是月平均，12 个时次正好一年；算年平均时每块刚好对应一年。
ds = xr.open_dataset(SRC, chunks={"time": 12})
# ---- 【取变量】文件里只有一个变量 wind；注意 CMFD 的维度叫 lat/lon，
#      ERA5 叫 latitude/longitude——两者合并时会因为这个差别对不上（见博客第八个坑）。
w = ds.wind

# ---- 【这三个打印是验收用的】形状说明读进来多少；chunks 说明真的分块了；
#      nbytes 只是"全读进来会占多少"，此刻一块都没读。
print("形状    :", w.shape)          # (480, 400, 700)
print("分块    :", w.chunks)         # ((12,12,...共40块), (400,), (700,))
print("整块大小:", round(w.nbytes / 1e6, 1), "MB")   # 537.6，除 1e6 是程序里的 MB

# ======================================================================
# 第二步：先降维，再聚合（顺序反了会浪费几十倍内存）
# ======================================================================
# ---- 【为什么先做区域平均】三维数组有 1.34 亿个格点，先沿 lat/lon 平均压成一维（480 个数），
#      后面所有操作都便宜几十倍。这是"先降维再聚合"的基本习惯。
# ---- 【两个括号别少】外层是函数调用，内层是元组（要消两个维度）；
#      写成 w.mean("lat", "lon") 会把 "lon" 当成第二个位置参数，直接报错。
reg = w.mean(("lat", "lon"))
# ---- 【判断惰性别看类型名】xarray 2026 会把底层包成 Array，打印出来看不出是不是 dask。
#      可靠办法是看 chunks：不是 None 就说明还没真算。
print("区域平均:", reg.shape, "chunks =", reg.chunks)

# ======================================================================
# 第三步：按年聚合，并在最后一步才触发计算
# ======================================================================
# ---- 【resample("1YS")】Y=Year，S=Start，按"每年 1 月 1 日"为起点重新分箱；
#      结果坐标是箱的左边界，所以是 1979-01-01、1980-01-01…，不是整数年份。
# ---- 【.mean()】每个箱内求平均 → 每年一个数（40 个值）。
# ---- 【.compute()】前面全是惰性任务图；这一句才真正读磁盘。
#      不写它 → annual 是个 dask 对象，打印出来是 <xarray.DataArray ...>，没有数字。
#      注意 compute 放在链条最后：只读一遍数据，比中途分开算省一半时间。
annual = reg.resample(time="1YS").mean().compute()

# ---- 【验算】480 个月 / 12 = 40 年；前 5 年打印出来对一下量级（应该是 2~3 m/s）。
print("年数    :", annual.sizes["time"])
print("前 5 年 :", np.round(annual.values[:5], 2))

# ======================================================================
# 第四步：画图
# ======================================================================
# ---- fig 是整张纸，ax 是纸上那一个坐标系。多子图时 ax 会变成数组。
fig, ax = plt.subplots(figsize=(10, 4))          # 10×4 英寸，宽高比适合 40 个点的折线
ax.plot(annual.time, annual.values, marker="o", ms=3)   # ms=点大小，40 个点用 3 刚好
ax.set_ylabel("风速 (m s$^{-1}$)")               # $^{-1}$ 是 LaTeX，渲染成上标
ax.set_title("CMFD 新疆区域平均风速 · 年平均（1979–2018）")
ax.grid(alpha=0.3)                               # 网格调淡，别抢数据
fig.autofmt_xdate()                              # 日期轴倾斜，否则 40 个年份标签叠成一团

# ======================================================================
# 第五步：保存
# ======================================================================
# ---- 【必须建目录】savefig 不会自动创建目录，目录不存在直接 FileNotFoundError；
#      exist_ok=True 让重复运行不报错。
OUT.parent.mkdir(parents=True, exist_ok=True)
# ---- dpi=150 够屏幕看；bbox_inches="tight" 自动裁掉白边，防止轴标签被切掉。
fig.savefig(OUT, dpi=150, bbox_inches="tight")
print("已保存:", OUT.name)        # .name 只取文件名，不打印长路径

